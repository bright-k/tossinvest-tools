#!/usr/bin/env python3
"""Derive the readonly typed dispatcher from the pinned generated Go signatures."""
import re
from pathlib import Path
s=Path('internal/broker/toss/generated/client.gen.go').read_text()
out=['// Code generated by scripts/generate-adapter.py; DO NOT EDIT.\npackage toss\n','import ("bytes";"encoding/json";"fmt";"io";"net/http";"strconv";g "github.com/bright-k/tossinvest-tools/internal/broker/toss/generated")\n', 'func BuildRequest(id, base string, args map[string]any, account string)(*http.Request,error){\n b,_:=json.Marshal(args); _=b; seq,_:=strconv.ParseInt(account,10,64); _=seq; switch id {']
ids=[]
for name,sig in re.findall(r'func New((?:Get|List)\w+)Request\((.*?)\) \(\*http.Request, error\)',s):
    ids.append(name)
    out.append('case "'+name[0].lower()+name[1:]+'":')
    call=['base']
    for arg in sig.split(', ')[1:]:
        var,typ=arg.split(' ')
        if var=='params':
            out.append(f'var p g.{typ[1:]}; if err:=json.Unmarshal(b,&p);err!=nil{{return nil,err}}')
            if 'XTossinvestAccount ' in re.search(r'type '+typ[1:]+r' struct \{(.*?)\n\}',s,re.S)[1]:
                out.append('p.XTossinvestAccount=g.AccountSeq(seq)')
            call.append('&p')
        else:
            if typ=='string':call.append('fmt.Sprint(args["'+var+'"])')
            else:call.append('g.'+typ+'(fmt.Sprint(args["'+var+'"]))')
    out.append('return g.New'+name+'Request('+','.join(call)+')')
out.append('};return nil,fmt.Errorf("unregistered read operation")}')
out.append('func DecodeTyped(id string, status int, b []byte) error {r:=&http.Response{StatusCode:status,Header:http.Header{"Content-Type":[]string{"application/json"}},Body:io.NopCloser(bytes.NewReader(b))}; switch id {')
for name in ids:out.append('case "'+name[0].lower()+name[1:]+'": _,err:=g.Parse'+name+'Response(r);return err')
out.append('};return fmt.Errorf("unregistered response")}')
Path('internal/broker/toss/dispatch.gen.go').write_text('\n'.join(out)+'\n')
